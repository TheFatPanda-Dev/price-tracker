import { chromium } from "playwright-core";
const [base, out] = process.argv.slice(2);
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await ctx.newPage();
  await page.goto(base + "/login");
  await page.screenshot({ path: `${out}/logo-login.png`, clip: { x: 0, y: 0, width: 600, height: 120 } });
  await page.fill('input[name="email"]', "admin@example.com");
  await page.fill('input[name="password"]', "sample-password-123");
  await page.click('button[type="submit"]');
  await page.waitForURL(base + "/");
  console.log("favicon:", await page.getAttribute('link[rel="icon"]', "href"), await page.getAttribute('link[rel="apple-touch-icon"]', "href"));
  const shop = page.locator('table a[target="_blank"]').first();
  console.log("desktop shop link:", await shop.getAttribute("href"), await shop.textContent());
  const [popup] = await Promise.all([ctx.waitForEvent("page"), shop.click()]);
  console.log("opened tab:", popup.url());
  await popup.close();
  await page.locator("table a[href^='/products/']:not([tabindex])").first().click();
  await page.waitForURL(/\/products\//);
  console.log("title link →", page.url());
  await page.goto(base + "/");
  await page.waitForTimeout(1200);
  await page.screenshot({ path: `${out}/links-desktop.png`, clip: { x: 0, y: 0, width: 1440, height: 520 } });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${out}/links-mobile.png` });
  const mshop = page.locator('ul a[target="_blank"]').first();
  const [p2] = await Promise.all([ctx.waitForEvent("page"), mshop.click()]);
  console.log("mobile shop tab:", p2.url());
  await p2.close();
  const box = await page.locator("ul li").first().boundingBox();
  await page.mouse.click(box!.x + 30, box!.y + box!.height - 8);
  await page.waitForURL(/\/products\//);
  console.log("mobile row tap →", page.url());
  await b.close();
})();
