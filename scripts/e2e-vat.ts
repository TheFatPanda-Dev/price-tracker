import { chromium } from "playwright-core";
const [base, out] = process.argv.slice(2);
(async () => {
  const b = await chromium.launch();
  const page = await b.newPage({ viewport: { width: 1440, height: 900 } });
  await page.goto(base + "/login");
  await page.fill('input[name="email"]', "admin@example.com");
  await page.fill('input[name="password"]', "sample-password-123");
  await page.click('button[type="submit"]');
  await page.waitForURL(base + "/");
  await page.goto(base + "/settings");
  const form = page.locator('form:has(input[name="showNetPrices"])');
  await form.locator('input[name="showNetPrices"]').check();
  await form.locator('button[type="submit"]').click();
  await form.locator('p[role="status"]').waitFor();
  console.log("settings:", await form.locator('p[role="status"]').textContent());
  await form.screenshot({ path: `${out}/vat-settings.png` });
  await page.goto(base + "/");
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${out}/vat-desktop.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${out}/vat-mobile.png` });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base + "/products/2");
  const ed = page.locator('form:has(input[name="vat"])');
  await ed.locator('input[name="vat"]').fill("19");
  await ed.locator('button[type="submit"]').click();
  await ed.locator('p[role="status"]').waitFor();
  console.log("product:", await ed.locator('p[role="status"]').textContent());
  await page.screenshot({ path: `${out}/vat-product.png` });
  await b.close();
})();
